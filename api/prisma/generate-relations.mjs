import { createInterface } from "node:readline";
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

// Métadonnées publiques du protocole des générateurs Prisma : la normalisation
// des écritures imbriquées ne dépend ainsi pas des internes du client généré.
for await (const line of createInterface({ input: process.stdin })) {
  const request = JSON.parse(line);
  let result = {};
  if (request.method === "getManifest") {
    result = { manifest: { prettyName: "Display field relations", defaultOutput: "../src/generated/relations" } };
  } else if (request.method === "generate") {
    const { dmmf, generator: { output } } = request.params;
    const relations = Object.fromEntries(dmmf.datamodel.models.map(model => [
      model.name,
      model.fields.filter(field => field.kind === "object")
        .map(({ name, type }) => ({ name, type })),
    ]));
    await mkdir(output.value, { recursive: true });
    await writeFile(join(output.value, "relations.ts"),
      "// Generated by prisma generate. Do not edit.\n" +
      "export const relationsByModel: Record<string, { name: string; type: string }[]> = " +
      JSON.stringify(relations, null, 2) + ";\n");
  }
  process.stderr.write(JSON.stringify({ jsonrpc: "2.0", id: request.id, result }) + "\n");
}
